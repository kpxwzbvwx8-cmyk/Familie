create or replace function public.give_strike(p_user uuid, p_rule uuid, p_reason text, p_photo text default null)
returns public.strikes
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.strike_rules;
  s public.strikes;
begin
  if not public.is_member() then raise exception 'Kein Mitglied'; end if;
  if p_user = auth.uid() then raise exception 'Du kannst dich nicht selbst bestrafen'; end if;
  if not exists (select 1 from public.profiles where family_id = public.current_family_id() and id = p_user) then raise exception 'Unbekannter Trainer'; end if;
  select * into r from public.strike_rules where family_id = public.current_family_id() and id = p_rule and approved_at is not null;
  if r.id is null then raise exception 'Diese Vorlage ist nicht (mehr) rechtskräftig'; end if;
  p_reason := trim(coalesce(p_reason, ''));
  if p_reason = '' then raise exception 'Bitte begründen, warum der Strich jetzt vergeben wird'; end if;
  insert into public.strikes (user_id, given_by, rule_id, title, description, value, reason, has_photo, history)
  values (p_user, auth.uid(), r.id, r.title, r.description, r.value, left(p_reason, 500), p_photo is not null,
          jsonb_build_array(public.log_entry('given', left(p_reason, 500))))
  returning * into s;
  if p_photo is not null then
    insert into public.strike_photos (strike_id, data) values (s.id, p_photo);
  end if;
  return s;
end;
$$;

create or replace function public.confirm_fine(p_user uuid)
returns public.fines
language plpgsql
security definer
set search_path = public
as $$
declare
  f public.fines;
  v_active numeric;
begin
  if not public.is_member() then raise exception 'Kein Mitglied'; end if;
  if not exists (select 1 from public.profiles where family_id = public.current_family_id() and id = p_user) then raise exception 'Unbekannter Trainer'; end if;
  perform 1 from public.profiles where family_id = public.current_family_id() and id = p_user for update;
  select coalesce((select sum(value) from public.strikes where user_id = p_user and status = 'active'), 0)
       - 10 * (select count(*) from public.fines where user_id = p_user and settled_at is not null)
    into v_active;
  if v_active < 10 then raise exception 'Erst wenn 10 Striche rechtskräftig sind, kann bezahlt werden'; end if;
  insert into public.fines (user_id) values (p_user) on conflict (user_id) where settled_at is null do nothing;
  update public.fines
     set confirmations = case when auth.uid() = any (confirmed_by) then confirmations
                              else confirmations || jsonb_build_object('by', auth.uid(), 'at', now()) end,
         confirmed_by = array(select distinct unnest(confirmed_by || auth.uid()))
   where user_id = p_user and settled_at is null
   returning * into f;
  if public.all_members_in(f.confirmed_by) then
    update public.fines set settled_at = now() where id = f.id returning * into f;
  end if;
  return f;
end;
$$;

create or replace function public.set_event_done(p_event uuid, p_occ timestamptz, p_done boolean)
returns void
