      using (family_id = (select public.current_family_id())) with check (family_id = (select public.current_family_id()))', t);
  end loop;
end;
$$;

create or replace function public.join_family(
  p_code text, p_first_name text, p_last_name text, p_gender text, p_color text, p_birthday date
) returns public.profiles language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  space_id integer;
  member public.profiles;
begin
  if uid is null then raise exception 'Nicht angemeldet'; end if;
  if exists (select from public.profiles where id = uid) then
    raise exception 'Dieses Gerät hat bereits ein Konto';
  end if;
  p_code := upper(btrim(coalesce(p_code, '')));
  if length(p_code) not between 4 and 40 then
    raise exception 'Der Familien-Code muss zwischen 4 und 40 Zeichen haben.';
  end if;
  -- Der eindeutige Code verbindet auch gleichzeitige erste Anmeldungen.
  insert into public.family(code) values (p_code)
    on conflict (code) do update set code = excluded.code returning id into space_id;
  loop
    insert into public.profiles(id, family_id, trainer_id, first_name, last_name, gender, color, birthday)
      values (uid, space_id, lpad(floor(random()*100000)::int::text, 5, '0'),
        btrim(p_first_name), btrim(p_last_name), p_gender, lower(p_color), p_birthday)
      on conflict (family_id, trainer_id) do nothing returning * into member;
    exit when found;
  end loop;
  return member;
end;
$$;

