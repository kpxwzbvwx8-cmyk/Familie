create or replace function public.set_task_note_check(p_message uuid, p_index integer, p_checked boolean)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  update public.messages
     set note_checks[p_index + 1] = p_checked
   where id = p_message and family_id = public.current_family_id() and attached_note is not null
     and done_by is null and closed_at is null and p_checked is not null
     and p_index between 0 and cardinality(note_checks) - 1
     and (case when cardinality(assignees) > 0 then auth.uid() = any(assignees)
               else auth.uid() <> author_id end);
  if not found then raise exception 'Dieser Listenpunkt kann nicht geändert werden.'; end if;
end;
$$;

create or replace function public.process_deadlines()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  m record;
  n integer := 0;
begin
  for m in
    select * from public.messages
    where deadline_at is not null and deadline_at <= now() and closed_at is null
    for update skip locked
  loop
    if m.threat_strike then
      continue when public.message_frozen(m.id);
      insert into public.strikes (user_id, message_id, given_by, title, description, value, reason, history)
      select p.id, m.id, m.author_id, 'Deadline verpasst', m.title, 1, 'Deadline verpasst: ' || m.title,
             jsonb_build_array(jsonb_build_object('type', 'given', 'by', m.author_id, 'at', now(), 'text', 'Deadline verpasst (automatisch)'))
      from public.profiles p
      where p.family_id = m.family_id and case when cardinality(m.assignees) > 0 then p.id = any (m.assignees) else p.id <> m.author_id end;
      update public.messages
         set closed_at = now(), review_status = 'missed', strike_note = 'Deadline verpasst'
       where id = m.id;
    else
      update public.messages set closed_at = now() where id = m.id;
    end if;
    n := n + 1;
  end loop;
  return n;
end;
$$;

