-- Supabase kann DELETE nach dem Entfernen der Zeile nicht mehr per RLS filtern.
-- Ein einziges, geschütztes Änderungssignal pro Familie stößt das Neuladen an.
create table public.family_refresh (
  family_id integer primary key references public.family on delete cascade,
  changed_at timestamptz not null default clock_timestamp()
);
alter table public.family_refresh enable row level security;
revoke all on public.family_refresh from public, anon, authenticated;
grant select on public.family_refresh to authenticated;
create policy family_scope on public.family_refresh for select to authenticated
  using (family_id = (select public.current_family_id()));

create function public.notify_family_deletion() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  space_id integer;
begin
  case tg_table_name
    when 'message_comments', 'message_responses' then
      select family_id into space_id from public.messages where id = old.message_id;
    when 'event_comments', 'event_invites', 'event_done' then
      select family_id into space_id from public.events where id = old.event_id;
    when 'strikes', 'fines' then
      select family_id into space_id from public.profiles where id = old.user_id;
    else space_id := old.family_id;
  end case;
  -- Bei kaskadierenden Löschungen signalisiert bereits die übergeordnete Karte.
  if space_id is not null then
    insert into public.family_refresh(family_id) values (space_id)
      on conflict (family_id) do update set changed_at = excluded.changed_at;
  end if;
  return old;
end;
$$;
revoke all on function public.notify_family_deletion() from public, anon, authenticated;
do $$
declare t text;
begin
  foreach t in array array['profiles','messages','notes','events','strike_rules','message_comments',
    'message_responses','event_comments','event_invites','event_done','strikes','fines'] loop
    execute format('create trigger notify_family_deletion before delete on public.%I
      for each row execute function public.notify_family_deletion()', t);
  end loop;
end;
$$;
alter publication supabase_realtime set (publish = 'insert, update');
alter publication supabase_realtime add table public.family_refresh;
