declare t text;
begin
  foreach t in array array['messages','events','notes','strike_rules'] loop
    execute format('alter table public.%I add column family_id integer not null default 1 references public.family(id)', t);
    execute format('alter table public.%I alter column family_id set default public.current_family_id()', t);
